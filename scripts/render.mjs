function renderDeploymentsPage() {
  const lines = [];
  lines.push("# Deployments");
  lines.push("");
  lines.push(MARKER);
  lines.push("");
  lines.push(renderMainnetSection());
  lines.push("");
  lines.push(renderSepoliaSection());
  lines.push("");
  return lines.join("\n");
}

// ---------- launch-configuration.md ----------

function renderLaunchConfigPage() {
  const lines = [];
  lines.push("# Launch configuration");
  lines.push("");
  lines.push(MARKER);
  lines.push("");
  lines.push(
    table(
      ["Key", "Value", "Unit", "Description"],
      config.entries.map((e) => [code(e.key), formatConfigValue(e), cell(e.unit), cell(e.description)])
    )
  );
  lines.push("");
  return lines.join("\n");
}

// ---------- contracts/README.md ----------

function findMainnetEntry(name) {
  return mainnet.contracts.find((c) => c.name === name);
}

function renderContractsIndexPage() {
  const lines = [];
  lines.push("# Contracts");
  lines.push("");
  lines.push(MARKER);
  lines.push("");
  const rows = reference.contracts.map((c) => {
    const slug = SLUGS[c.name];
    const entry = findMainnetEntry(c.name);
    const addressCell = entry ? addressLink(entry.address, mainnet.chainId) : "Deployed per application";
    return [
      `[${cell(c.name)}](${slug}.md)`,
      code(c.source),
      addressCell,
      String(c.functions.length),
      String(c.events.length),
      String(c.errors.length),
    ];
  });
  lines.push(table(["Contract", "Source", "Address", "Functions", "Events", "Errors"], rows));
  lines.push("");
  return lines.join("\n");
}

// ---------- contracts/<slug>.md ----------

function renderFunctionDetails(fn) {
  const hasDev = fn.dev && fn.dev.length > 0;
  const hasParams = fn.params && Object.keys(fn.params).length > 0;
  if (!hasDev && !hasParams) return null;

  const lines = [];
  lines.push("<details>");
  lines.push(`<summary>${code(fn.signature)}</summary>`);
  lines.push("");
  if (hasDev) {
    lines.push(noDash(fn.dev));
    lines.push("");
  }
  if (hasParams) {
    lines.push("Parameters:");
    lines.push("");
    for (const input of fn.inputs) {
      if (!(input.name in fn.params)) continue;
      lines.push(`- ${code(input.name)} (${code(input.type)}): ${noDash(fn.params[input.name])}`);
    }
    lines.push("");
  }
  lines.push("</details>");
  return lines.join("\n");
}

function renderFunctionGroup(title, fns) {
  if (!fns.length) return [];
  const lines = [];
  lines.push(`### ${title}`);
  lines.push("");
  lines.push(table(["Function", "Notice"], fns.map((f) => [code(f.signature), cell(f.notice)])));

  const details = fns.map(renderFunctionDetails).filter(Boolean);
  if (details.length) {
    lines.push("");
    lines.push(details.join("\n\n"));
  }
  return lines;
}

function renderEventsSection(events) {
  if (!events.length) return [];
  const lines = [];
  lines.push("## Events");
  lines.push("");
  const rows = events.map((e) => {
    const topicCell = e.topic0
      ? `${code(e.signature)}<br><details><summary>${code(truncateHash(e.topic0))}</summary>${code(
          e.topic0
        )}</details>`
      : code(e.signature);
    return [topicCell, cell(e.notice)];
  });
  lines.push(table(["Event", "Notice"], rows));
  return lines;
}

function renderErrorsSection(errors) {
  if (!errors.length) return [];
  const lines = [];
  lines.push("## Errors");
  lines.push("");
  lines.push(
    table(
      ["Error", "Selector", "Notice"],
      errors.map((e) => [code(e.signature), code(e.selector), cell(e.notice)])
    )
  );
  return lines;
}

function renderContractPage(c) {
  const lines = [];
  lines.push(`# ${c.name}`);
  lines.push("");
  lines.push(MARKER);
  lines.push("");

  if (c.notice) {
    lines.push(noDash(c.notice));
    lines.push("");
  }

  if (c.name === "MidwayBatchAccount") {
    lines.push("**Address**: deployed per application as a clone of the implementation.");
  } else {
    const entry = findMainnetEntry(c.name);
    if (entry) {
      lines.push(`**Address**: ${addressLink(entry.address, mainnet.chainId)}`);
      if (c.name === "RequestBuyer") {
        lines.push("");
        lines.push("The listed address is the implementation cloned per request.");
      }
    }
  }
  lines.push(`**Source**: ${code(c.source)}`);
  lines.push("");

  lines.push("## Functions");
  lines.push("");
  const stateChanging = c.functions.filter((f) => f.stateMutability === "nonpayable" || f.stateMutability === "payable");
  const viewFns = c.functions.filter((f) => f.stateMutability === "view" || f.stateMutability === "pure");
  const fnLines = [
    ...renderFunctionGroup("State changing", stateChanging),
    ...(stateChanging.length && viewFns.length ? [""] : []),
    ...renderFunctionGroup("View", viewFns),
  ];
  lines.push(...fnLines);
  lines.push("");

  const eventLines = renderEventsSection(c.events);
  if (eventLines.length) {
    lines.push(...eventLines);
    lines.push("");
  }

  const errorLines = renderErrorsSection(c.errors);
  if (errorLines.length) {
    lines.push(...errorLines);
    lines.push("");
  }

  return lines.join("\n");
}

// ---------- write ----------

function writePage(relPath, content) {
  const full = path.join(outDir, relPath);
  mkdirSync(path.dirname(full), { recursive: true });
  // single trailing newline, no trailing whitespace on lines
  const normalized = content
    .split("\n")
    .map((l) => l.replace(/[ \t]+$/, ""))
    .join("\n")
    .replace(/\n+$/, "") + "\n";
  writeFileSync(full, normalized);
}

writePage("deployments.md", renderDeploymentsPage());
writePage("launch-configuration.md", renderLaunchConfigPage());
writePage(path.join("contracts", "README.md"), renderContractsIndexPage());
for (const c of reference.contracts) {
  const slug = SLUGS[c.name];
  if (!slug) throw new Error(`no slug mapping for contract ${c.name}`);
  writePage(path.join("contracts", `${slug}.md`), renderContractPage(c));
}

console.log(`rendered ${2 + 1 + reference.contracts.length} page(s) into ${path.relative(root, outDir)}`);
